// build gradle
// @params none

import com.android.build.gradle.BaseExtension

allprojects {
    repositories {
        google()
        mavenCentral()
    }
}

val newBuildDir: Directory =
    rootProject.layout.buildDirectory
        .dir("../../build")
        .get()

rootProject.layout.buildDirectory.value(newBuildDir)

subprojects {
    val newSubprojectBuildDir: Directory =
        newBuildDir.dir(project.name)

    project.layout.buildDirectory.value(newSubprojectBuildDir)
}

subprojects {
    // a few Flutter plugins still publish library modules with an older
    // compile sdk, while their androidx dependencies require api 34+
    // keep their runtime and min sdk behavior unchanged and only align the
    // compile surface used by Gradle's aar metadata checks
    plugins.withId("com.android.application") {
        extensions.configure<com.android.build.api.dsl.ApplicationExtension> {
            compileSdk = 36
        }
    }
    plugins.withId("com.android.library") {
        extensions.configure<com.android.build.api.dsl.LibraryExtension> {
            compileSdk = 36
        }
    }

    afterEvaluate {
        // flutter_windowmanager_plus still writes compileSdkVersion 33 in
        // its legacy groovy block after plugin callbacks have run
        @Suppress("DEPRECATION")
        extensions.findByType<BaseExtension>()?.compileSdkVersion(36)
    }
}

subprojects {
    project.evaluationDependsOn(":app")
}

tasks.register<Delete>("clean") {
    delete(rootProject.layout.buildDirectory)
}
